"""Attach evidence to facts in the model response; code owns final citation paths."""

import copy
import json


STATUSES = ['found', 'not_located', 'ambiguous', 'conflicting', 'missing_document']
CITATION = {'type': 'object', 'additionalProperties': False,
            'properties': {'evidence_id': {'type': 'string'}, 'quote': {'type': 'string'}},
            'required': ['evidence_id', 'quote']}


class InlineFactError(ValueError):
    def __init__(self, field_path, check):
        super().__init__('Unresolved fact needs null and an explanation')
        self.field_path, self.check = field_path, check


def inline_schema(schema):
    """Reuse the typed application contract, wrapping each scalar rather than duplicating it."""
    schema = copy.deepcopy(schema)
    fact_definitions, fact_names = {}, {}

    def fact(value_schema):
        value_schema = {key: value for key, value in value_schema.items() if key != 'title'}
        signature = json.dumps(value_schema, sort_keys=True)
        if signature in fact_names:
            return {'$ref': f'#/$defs/{fact_names[signature]}'}
        name = f'InlineFact{len(fact_names)}'
        fact_names[signature] = name
        fact_definitions[name] = {'type': 'object', 'additionalProperties': False, 'properties': {
            'value': value_schema, 'status': {'type': 'string', 'enum': STATUSES},
            'evidence': {'type': 'array', 'items': {'$ref': '#/$defs/InlineCitation'}},
            'reason': {'anyOf': [{'type': 'string'}, {'type': 'null'}]},
            'scope': {'type': 'string', 'enum': ['post', 'shared', 'unknown']},
            'scope_evidence': {'type': 'array', 'items': {'$ref': '#/$defs/InlineCitation'}}},
            'required': ['value', 'status', 'evidence', 'reason', 'scope', 'scope_evidence']}
        return {'$ref': f'#/$defs/{name}'}

    def wrap(node):
        if '$ref' in node:
            return node
        if node.get('type') == 'object':
            node['properties'] = {key: wrap(value) for key, value in node['properties'].items()}
            return node
        if node.get('type') == 'array':
            node['items'] = wrap(node['items'])
            return node
        if 'anyOf' in node and any('$ref' in item for item in node['anyOf']):
            node['anyOf'] = [wrap(item) for item in node['anyOf']]
            return node
        return fact(node)

    # Evidence and missing reasons are generated by code, not repeated by the model.
    schema['properties'] = {'posts': schema['properties']['posts']}
    schema['required'] = ['posts']
    schema['$defs'] = {name: wrap(definition) for name, definition in schema['$defs'].items()
                       if name not in {'FieldEvidence', 'MissingField'}}
    schema['$defs'].update(fact_definitions)
    schema['$defs']['InlineCitation'] = copy.deepcopy(CITATION)
    return schema


def decode_inline(response, source):
    """Validate local quote/scope evidence and flatten facts without inventing citations."""
    from build_extraction_input import BundleFacts

    if not isinstance(response, dict) or not isinstance(response.get('posts'), list):
        raise ValueError('Invalid inline response root')
    response = copy.deepcopy(response)
    units = {unit['evidence_id']: unit for document in source['documents'] for unit in document['sections']}
    facts = {
        'purpose': response.get('purpose', 'recruitment'),
        'purpose_evidence': response.get('purpose_evidence', []),
        'document_purposes': response.get('document_purposes', []),
        'amendment': response.get('amendment'),
        'posts': [],
        'evidence': [],
        'missing_fields': [],
    }
    checks, errors = [], []

    def validate_quotes(citations, path, kind):
        if not isinstance(citations, list):
            raise ValueError('Invalid evidence list')
        valid = []
        for citation in citations:
            if not isinstance(citation, dict) or set(citation) != {'evidence_id', 'quote'}:
                raise ValueError('Invalid inline citation')
            identifier, quote = citation['evidence_id'], citation['quote']
            if not isinstance(identifier, str) or not isinstance(quote, str):
                raise ValueError('Invalid inline citation types')
            unit = units.get(identifier)
            if not unit or not quote.strip() or quote not in unit['text'] or not unit['locations']:
                errors.append({'field_path': path, 'reason': f'{kind}_quote_not_located'})
            else:
                valid.append(citation)
        return valid

    # Validate purpose evidence citations
    if facts['purpose_evidence']:
        facts['purpose_evidence'] = validate_quotes(facts['purpose_evidence'], 'purpose_evidence', 'purpose')

    # Validate document purposes evidence citations if present
    for dp_idx, dp in enumerate(facts['document_purposes']):
        if isinstance(dp, dict) and 'evidence' in dp:
            dp['evidence'] = validate_quotes(dp['evidence'], f'document_purposes.{dp_idx}', 'document_purpose')

    # Validate amendment citations if present
    if isinstance(facts['amendment'], dict) and 'evidence' in facts['amendment']:
        facts['amendment']['evidence'] = validate_quotes(facts['amendment']['evidence'], 'amendment', 'amendment')

    def flatten(node, path):
        if isinstance(node, list):
            return [flatten(value, f'{path}.{index}') for index, value in enumerate(node)]
        if isinstance(node, dict) and 'value' not in node:
            return {key: flatten(value, f'{path}.{key}') for key, value in node.items()}
        required = {'value', 'status', 'evidence', 'reason', 'scope', 'scope_evidence'}
        if not isinstance(node, dict) or set(node) != required:
            raise ValueError('Every scalar needs an inline fact')
        value, status, reason = node['value'], node['status'], node['reason']
        if status not in STATUSES or node['scope'] not in {'post', 'shared', 'unknown'}:
            raise ValueError('Invalid fact status or scope')
        if reason is not None and not isinstance(reason, str):
            raise ValueError('Invalid missing reason')
        if status == 'found':
            if value is None or not node['evidence']:
                raise ValueError('Found fact needs a value and evidence')
        elif value is not None:
            raise InlineFactError(path, 'unresolved_value_not_null')
        elif not isinstance(reason, str) or not reason.strip():
            raise InlineFactError(path, 'unresolved_explanation_missing')
        citations = validate_quotes(node['evidence'], path, 'fact')
        scope = validate_quotes(node['scope_evidence'], path, 'scope')
        if status == 'found':
            facts['evidence'].extend({'field_path': path, **citation} for citation in citations)
            if node['scope'] == 'unknown' or not scope:
                errors.append({'field_path': path, 'reason': 'scope_needs_review'})
        else:
            facts['missing_fields'].append({'field_path': path, 'reason': f'{status}: {reason}'})
        checks.append({'field_path': path, 'status': status, 'scope': node['scope'],
                       'reason': reason, 'evidence': node['evidence'],
                       'scope_evidence': node['scope_evidence']})
        return value

    facts['posts'] = flatten(response['posts'], 'posts')
    # JSON validation retains date support while enforcing the original numeric types.
    facts = BundleFacts.model_validate_json(json.dumps(facts), strict=True).model_dump(mode='json')
    return facts, {'status': 'needs_review' if errors else 'quotes_located',
                   'errors': errors, 'fields': checks, 'semantic_support_verified': False}
